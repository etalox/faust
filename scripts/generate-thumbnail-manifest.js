const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const sourceDirectory = path.join(root, 'assets', 'Thumbnails');
const outputPath = path.join(sourceDirectory, 'brucolastic-manifest.js');
const galleryPath = path.join(root, 'storage', 'thumbnails', 'brucolastic.html');
const supportedExtensions = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.webp']);

const thumbnails = fs.readdirSync(sourceDirectory, { withFileTypes: true })
  .filter((entry) => entry.isFile() && supportedExtensions.has(path.extname(entry.name).toLowerCase()))
  .map((entry) => {
    const filePath = path.join(sourceDirectory, entry.name);
    return { file: entry.name, modified: Math.round(fs.statSync(filePath).mtimeMs) };
  })
  .sort((a, b) => b.modified - a.modified);

const manifest = `/* Generated by scripts/generate-thumbnail-manifest.js. Do not edit manually. */\n` +
  `window.BRUCOLASTIC_THUMBNAILS = ${JSON.stringify(thumbnails, null, 2)};\n`;

fs.writeFileSync(outputPath, manifest, 'utf8');

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  }[character]));
}

function card(item, isLatest) {
  const safeFile = escapeHtml(item.file);
  const source = `/assets/Thumbnails/${encodeURIComponent(item.file)}`;
  return `        <a class="thumbnail${isLatest ? ' thumbnail--latest' : ''} is-loaded" href="${source}" download="${safeFile}" data-thumbnail-file="${safeFile}" aria-label="Descargar ${safeFile}">
          <img class="thumbnail__image" src="${source}" alt="${safeFile}" decoding="async">
          <span class="thumbnail__veil" aria-hidden="true"><span class="thumbnail__action">Descargar</span></span>
        </a>`;
}

const latestStart = '<!-- thumbnails:generated:latest:start -->';
const latestEnd = '<!-- thumbnails:generated:latest:end -->';
const gridStart = '<!-- thumbnails:generated:grid:start -->';
const gridEnd = '<!-- thumbnails:generated:grid:end -->';
let gallery = fs.readFileSync(galleryPath, 'utf8');

function replaceGeneratedBlock(source, start, end, content) {
  const pattern = new RegExp(`${start}\\s*[\\s\\S]*?\\s*${end}`);
  if (!pattern.test(source)) throw new Error(`Gallery marker not found: ${start}`);
  return source.replace(pattern, `${start}\n${content}\n        ${end}`);
}

gallery = replaceGeneratedBlock(gallery, latestStart, latestEnd, thumbnails[0] ? card(thumbnails[0], true) : '');
gallery = replaceGeneratedBlock(gallery, gridStart, gridEnd, thumbnails.slice(1).map((item) => card(item, false)).join('\n'));
fs.writeFileSync(galleryPath, gallery, 'utf8');

console.log(`Generated thumbnail manifest and gallery with ${thumbnails.length} image(s).`);
